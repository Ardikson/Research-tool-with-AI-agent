  // Промежуточный сигнал, хранящий поисковый запрос, который применится при нажатии Enter или кнопки
  appliedSearchQuery = signal('');

  constructor(private router: Router) {}

  // ВЫЧИСЛЯЕМЫЙ ФИЛЬТР: Срабатывает при обновлении appliedSearchQuery или selectedCategory
filteredScientists = computed(() => {
  let list = this.scientists();
  const cat = this.selectedCategory();
  const query = this.searchQuery().toLowerCase().trim();

  // 1. Сначала фильтруем по категории (если выбрана конкретная наука)
  if (cat !== 'Все науки') {
    list = list.filter(s => s.field === cat);
  }

  // 2. Затем сразу же фильтруем по строке поиска
  if (query) {
    list = list.filter(s => s.name.toLowerCase().includes(query));
  }

  return list;
});


  // Логика живого ввода: сбрасывает поиск, если строка полностью очищена пользователем
  onSearchInput(value: string) {
    if (!value.trim()) {
      this.appliedSearchQuery.set('');
      this.searchQuery.set('');
    } else {
      this.searchQuery.set(value);
    }
  }

  // Запуск поиска по нажатию кнопки или кнопки Enter
  triggerSearch(value: string) {
    this.appliedSearchQuery.set(value);
    this.searchQuery.set(value);
  }

  // Очистка строки поиска через крестик
  clearSearch(inputElement: HTMLInputElement) {
    inputElement.value = '';
    this.searchQuery.set('');
    this.appliedSearchQuery.set('');
  }

  // Смена вкладки науки
  selectCategory(cat: string) {
    this.selectedCategory.set(cat);
  }

  // Полный сброс параметров
resetAllFilters() {
  this.searchQuery.set('');
  this.selectedCategory.set('Все науки');
}

  openScientist(s: Scientist) { this.activeScientist.set(s); }
  closeScientist() { this.activeScientist.set(null); }
  goToMain() { this.router.navigate(['/']); }
